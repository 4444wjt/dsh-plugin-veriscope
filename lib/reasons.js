export function reasonMessage(code) {
  return Object.hasOwn(REASONS, code) ? REASONS[code] : `${String(code)}（未收录）`
}
export const reasonMessages = codes => codes.map(reasonMessage)
export const renderReasons = codes => codes.map(code => `${reasonMessage(code)} [${code}]`).join('；')
